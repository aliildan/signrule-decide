"""Generate Markdown tables from results/<jur>-<split>/*.<part>.json (never typed by hand).

uv run python eval/make_tables.py --split random --part test
"""

from __future__ import annotations

import argparse
import json
import sys

from signrule.common.paths import REPO_ROOT

QUESTIONS = [
    "rule_type",
    "min_signers",
    "ceo_alone",
    "chair_alone",
    "two_board_members_jointly",
    "ceo_with_one_board_member",
    "prokura_present",
    "prokura_joint",
    "parseable",
    "ambiguity",
]
SHORT = {
    "rule_type": "rule_type",
    "min_signers": "min_sign",
    "ceo_alone": "ceo_alone",
    "chair_alone": "chair_alone",
    "two_board_members_jointly": "two_bm",
    "ceo_with_one_board_member": "ceo+bm",
    "prokura_present": "prok_pres",
    "prokura_joint": "prok_joint",
    "parseable": "parseable",
    "ambiguity": "ambig",
}


def fmt(x: float | None, pct: bool = True) -> str:
    if x is None:
        return "–"
    return f"{100 * x:.1f}" if pct else f"{x:.3f}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--jurisdiction", default="no")
    ap.add_argument("--split", default="random")
    ap.add_argument("--part", default="test")
    args = ap.parse_args(argv)
    d = REPO_ROOT / "results" / f"{args.jurisdiction}-{args.split}"
    files = sorted(d.glob(f"*.{args.part}.json"))
    if not files:
        raise SystemExit(f"no results in {d}")
    rows = [json.loads(f.read_text()) for f in files]
    out = [
        f"# {args.jurisdiction.upper()} · {args.split} · {args.part}",
        "",
        "Generated by `eval/make_tables.py` from `results/`; calibrated = temperature per question "
        "type fitted on val. Accuracy in %, n = items per question.",
        "",
        "## Accuracy per question (calibrated, %)",
        "",
        "| model | " + " | ".join(SHORT[q] for q in QUESTIONS) + " | mean |",
        "|---" * (len(QUESTIONS) + 2) + "|",
    ]
    for r in rows:
        accs = []
        cells = []
        for q in QUESTIONS:
            blk = (r["per_question"].get(q) or {}).get("calibrated") or {}
            a = blk.get("accuracy")
            cells.append(fmt(a))
            if a is not None:
                accs.append(a)
        mean = sum(accs) / len(accs) if accs else None
        out.append(f"| {r['model']} | " + " | ".join(cells) + f" | **{fmt(mean)}** |")
    n_row = rows[0]["per_question"]
    out.append(
        "| n | "
        + " | ".join(str((n_row.get(q) or {}).get("raw", {}).get("n", "–")) for q in QUESTIONS)
        + " | |"
    )
    out += [
        "",
        "## Calibration and selective prediction per question type",
        "",
        "| model | type | acc | ECE mass | ECE width | Brier | AURC "
        "| LTT cov @1% | @2% | @5% | test risk @2% |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        for qt in ("choice", "noul", "score"):
            blk = (r["per_type"].get(qt) or {}).get("calibrated")
            if not blk:
                continue
            ltt = blk.get("ltt", {})
            out.append(
                f"| {r['model']} | {qt} | {fmt(blk['accuracy'])} | {fmt(blk['ece_mass'], False)} | "
                f"{fmt(blk['ece_width'], False)} | {fmt(blk['brier'], False)} | "
                f"{fmt(blk['aurc'], False)} | "
                + " | ".join(fmt(ltt.get(a, {}).get("coverage")) for a in ("0.01", "0.02", "0.05"))
                + f" | {fmt(ltt.get('0.02', {}).get('risk'))} |"
            )
    tables = REPO_ROOT / "results" / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    path = tables / f"{args.jurisdiction}-{args.split}.{args.part}.md"
    path.write_text("\n".join(out) + "\n")
    print(path.relative_to(REPO_ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
